// ── Helper functions ─────────────────────────────────────────

let currentLang = (function () {
  const q = new URLSearchParams(location.search).get("lang");
  const v = (q || localStorage.getItem("ucl_lang") || "it").toLowerCase();
  return (v === "it" || v === "en") ? v : "it";
})();

function t(key, vars) {
  const keys = key.split(".");
  let val = TRANSLATIONS[currentLang];
  for (const k of keys) {
    if (val == null) return key;
    val = val[k];
  }
  if (val == null) return key;
  if (vars && typeof val === "string") {
    val = val.replace(/\{(\w+)\}/g, (m, p) => (p in vars ? vars[p] : m));
  }
  return val;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem("ucl_lang", lang);
  document.documentElement.lang = lang;
  applyTranslations();
  // Re-populate JS-built giornata selects with the new language
  if (typeof populateGiornataSelects === "function") populateGiornataSelects();
  // Re-render current page to update dynamic content
  if (typeof renderPage === "function" && typeof currentPage === "function") {
    renderPage(currentPage());
  }
}

function toggleLang() {
  setLang(currentLang === "it" ? "en" : "it");
}

function applyTranslations() {
  document.documentElement.lang = currentLang;
  // Text/HTML content (use innerHTML to support <strong>, <br> etc.)
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const val = t(el.dataset.i18n);
    if (val !== el.dataset.i18n) el.innerHTML = val;
  });
  // Placeholders
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const val = t(el.dataset.i18nPh);
    if (val !== el.dataset.i18nPh) el.placeholder = val;
  });
  // Title attributes
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    const val = t(el.dataset.i18nTitle);
    if (val !== el.dataset.i18nTitle) el.title = val;
  });
  // Document title
  document.title = t("meta.title");
  // Language switcher button
  const btn = document.getElementById("langSwitcher");
  if (btn) btn.textContent = currentLang === "it" ? "🇬🇧 EN" : "🇮🇹 IT";
}
